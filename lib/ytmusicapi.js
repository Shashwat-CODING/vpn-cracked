  _parseMusicItem(item) {
    if (!item) return null;
    const title = item.flexColumns?.[0]?.musicResponsiveListItemFlexColumnRenderer?.text?.runs?.[0]?.text;
    const subtitle = item.flexColumns?.[1]?.musicResponsiveListItemFlexColumnRenderer?.text?.runs || [];
    const thumbnail = item.thumbnail?.musicThumbnailRenderer?.thumbnail?.thumbnails?.[0]?.url;
    const watchEndpoint = item.overlay?.musicItemThumbnailOverlayRenderer?.content?.musicPlayButtonRenderer?.playNavigationEndpoint?.watchEndpoint;
    const videoId = watchEndpoint?.videoId;
    let watchPlaylistId = watchEndpoint?.playlistId;

    if (!watchPlaylistId && item.menu?.menuRenderer?.items) {
      const mixItem = item.menu.menuRenderer.items.find(i => i.menuNavigationItemRenderer?.icon?.iconType === 'MIX');
      if (mixItem) watchPlaylistId = mixItem.menuNavigationItemRenderer.navigationEndpoint?.watchEndpoint?.playlistId;
    }

    const browseId = item.navigationEndpoint?.browseEndpoint?.browseId;
    const playlistId = item.navigationEndpoint?.browseEndpoint?.browseEndpointContextSupportedConfigs?.browseEndpointContextMusicConfig?.pageType === 'MUSIC_PAGE_TYPE_PLAYLIST' ? item.navigationEndpoint?.browseEndpoint?.browseId : null;

    let duration = item.fixedColumns?.[0]?.musicResponsiveListItemFixedColumnRenderer?.text?.runs?.[0]?.text;
    if (!duration) {
      for (const run of subtitle) {
        const text = (run?.text || '').trim();
        const match = text.match(/\b(?:(\d{1,2}):)?(\d{1,2}):(\d{2})\b/) || text.match(/\b(\d{1,2}):(\d{2})\b/);
        if (match) {
          duration = text;
          break;
        }
      }
    }

    const artists = [];
    let album = null, views = null, year = null;
    subtitle.forEach((run, index) => {
      if (run.navigationEndpoint?.browseEndpoint) {
        const pageType = run.navigationEndpoint.browseEndpoint.browseEndpointContextSupportedConfigs?.browseEndpointContextMusicConfig?.pageType;
        if (pageType === 'MUSIC_PAGE_TYPE_ARTIST' || pageType === 'MUSIC_PAGE_TYPE_USER_CHANNEL') artists.push({ name: run.text, id: run.navigationEndpoint.browseEndpoint.browseId });
        else if (pageType === 'MUSIC_PAGE_TYPE_ALBUM') album = { name: run.text, id: run.navigationEndpoint.browseEndpoint.browseId };
      } else if (run.text) {
        const text = run.text.trim();
        if (!text || text === '•' || text === '&') return;
        if (text.includes('views') || text.includes('plays')) views = text;
        else if (/^\d{4}$/.test(text)) year = text;
        else if (index === 0 || artists.length === 0) artists.push({ name: text, id: null });
      }
    });

    const resultType = playlistId ? 'playlist' : browseId?.startsWith('UC') ? 'artist' : browseId?.startsWith('MPREb_') ? 'album' : 'song';
    const result = {
      category: resultType.charAt(0).toUpperCase() + resultType.slice(1) + 's',
      resultType,
      title,
      thumbnails: (item.thumbnail?.musicThumbnailRenderer?.thumbnail?.thumbnails || []).map(t => ({ url: t.url, width: t.width, height: t.height })),
      isExplicit: item.badges?.some(b => b.musicInlineBadgeRenderer?.icon?.iconType === 'MUSIC_EXPLICIT_BADGE') || false
    };

    if (watchPlaylistId) result.playlistId = watchPlaylistId;
    if (videoId) {
      result.videoId = videoId;
      result.duration = duration;
      result.videoType = 'MUSIC_VIDEO_TYPE_ATV';
    }
    if (artists.length > 0) result.artists = artists;
    if (album) result.album = album;
    if (browseId) result.browseId = browseId;
    if (views) result.views = views;
    if (year) result.year = year;
    return result;
  }

  _parseTracksFromContents(contents) {
    const tracks = [];
    contents.forEach(section => {
      if (section.musicShelfRenderer) {
        (section.musicShelfRenderer.contents || []).forEach(item => {
          if (item.musicResponsiveListItemRenderer) {
            const parsed = this._parseMusicItem(item.musicResponsiveListItemRenderer);
            if (parsed) tracks.push(parsed);
          }
        });
      }
    });
    return tracks;
  }

